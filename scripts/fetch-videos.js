#!/usr/bin/env node
/*
 * Build js/videos.js: YouTube videos of creators playing career modes like each
 * challenge type (a League Two rebuild for Road to Glory, a youth-academy-only
 * save for Youth Revolution...), for the 📺 Watch section on challenges.
 * Each type gets the top results of a YouTube search for it, with the title,
 * channel and length; the app plays them in YouTube's embedded player.
 *
 *   node scripts/fetch-videos.js     # add NODE_USE_ENV_PROXY=1 behind a proxy
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'js', 'videos.js');
const PER_TYPE = 8;

// What to search YouTube for, per challenge type.
const QUERIES = {
  'road-to-glory': 'FC 26 career mode road to glory lower league rebuild',
  'youth-revolution': 'FC 26 career mode youth academy only challenge',
  moneyball: 'FC 26 career mode moneyball challenge',
  'fallen-giant': 'FC 26 career mode fallen giant rebuild',
  homegrown: 'FC 26 career mode homegrown players only challenge',
  'loan-army': 'FC 26 career mode loan players only challenge',
  journeyman: 'FC 26 career mode journeyman manager challenge',
  galacticos: 'FC 26 career mode galacticos superteam',
  'underdog-europe': 'FC 26 career mode underdog champions league',
  'one-nation': 'FC 26 career mode one nationality only challenge',
  veterans: 'FC 26 career mode old players only challenge',
  'wonderkid-factory': 'FC 26 career mode wonderkids challenge',
  'club-heritage': 'FC 26 career mode realistic rebuild',
  chaos: 'FC 26 career mode random challenge',
  'one-club-legend': 'FC 26 player career one club legend',
  wonderkid: 'FC 26 player career wonderkid',
  'hometown-hero': 'FC 26 player career hometown club',
  'dream-move': 'FC 26 player career dream move',
  globetrotter: 'FC 26 player career every league',
  'last-line': 'FC 26 player career goalkeeper',
  'goal-machine': 'FC 26 player career striker goals record',
  'goalscoring-defender': 'FC 26 player career defender',
  'wildcard-career': 'FC 26 player career challenge',
  // For any type that comes back empty.
  general: 'FC 26 career mode challenge ideas',
};

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function search(q, attempt = 0) {
  try {
    return await searchOnce(q);
  } catch (e) {
    if (attempt >= 3) throw e;
    await sleep(3000 * (attempt + 1));
    return search(q, attempt + 1);
  }
}

async function searchOnce(q) {
  const r = await fetch(`https://www.youtube.com/results?${new URLSearchParams({ search_query: q, hl: 'en', gl: 'GB' })}`, {
    headers: { 'User-Agent': 'Mozilla/5.0', 'Accept-Language': 'en' },
  });
  const html = await r.text();
  const m = html.match(/var ytInitialData = (\{.*?\});<\/script>/s);
  if (!m) throw new Error(`No results page for "${q}"`);
  const found = [];
  (function walk(o) {
    if (Array.isArray(o)) { o.forEach(walk); return; }
    if (!o || typeof o !== 'object') return;
    if (o.videoRenderer) {
      const v = o.videoRenderer;
      const text = (x) => ((x && x.runs) || []).map((t) => t.text).join('') || (x && x.simpleText) || '';
      found.push({ id: v.videoId, title: text(v.title), channel: text(v.ownerText), length: text(v.lengthText), age: text(v.publishedTimeText) });
    }
    Object.values(o).forEach(walk);
  })(JSON.parse(m[1]));
  // Full videos (3 minutes or more, so no Shorts or live streams) about FC 26 or career mode.
  const seconds = (len) => len.split(':').map(Number).reduce((a, b) => a * 60 + b, 0);
  return found.filter((v) => v.id && /^\d+(:\d\d){1,2}$/.test(v.length) && seconds(v.length) >= 180
    && /fc ?2[56]|career|academy|rebuild|manager|wonderkid|club/i.test(v.title)
    // Not about another game.
    && !/fc ?2[47-9]|fifa ?\d\d|\bfm ?\d\d|football manager|efootball|pes ?\d/i.test(v.title));
}

async function main() {
  // A type whose search fails keeps the videos it had.
  let before = {};
  try { require(OUT); before = (globalThis.FC26.videos || {}).byType || {}; } catch (e) { before = {}; }
  const out = {};
  for (const [type, q] of Object.entries(QUERIES)) {
    try {
      const list = await search(q);
      const seen = new Set();
      out[type] = list.filter((v) => !seen.has(v.id) && seen.add(v.id)).slice(0, PER_TYPE)
        .map((v) => ({ id: v.id, title: v.title.slice(0, 120), channel: v.channel.slice(0, 60), length: v.length }));
      console.log(`${type}: ${out[type].length}`);
    } catch (e) {
      console.warn(`${type}: ${e.message}${before[type] ? ' (kept the old list)' : ''}`);
      if (before[type]) out[type] = before[type];
    }
    await sleep(800);
  }
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(OUT, `/*
 * Generated by scripts/fetch-videos.js on ${today}. Do not edit by hand.
 * YouTube videos of creators playing career modes like each challenge type
 * (challenge type id → [{ id, title, channel, length }]), from a YouTube search per type.
 */
(function (root) {
  'use strict';
  const FC26 = (root.FC26 = root.FC26 || {});
  FC26.videos = ${JSON.stringify({ fetched: today, byType: out, queries: QUERIES })};
})(typeof window !== 'undefined' ? window : globalThis);
`);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
